//! This file implements the GOOS (Scheme) objects and GC.
//! The objects are used by the GOOS macro evaluator and as the syntax representation for the
//! compiler. The garbage collector is relatively simple and currently cannot run during
//! evaluation.

use crate::intern::SymId;
use crate::read::SpanRef;
use std::collections::BTreeMap;

/// Placeholder type to represent a GOOS "builtin" as an object.
/// This allows users to do something like (map foo +) and it uses the built-in + implementation.
#[derive(Clone, Copy)]
struct BuiltinId(u32);

/// GOOS strings are mutable and have reference semantics.
/// A string is represented by an index into the string arena.
#[derive(Clone, Copy)]
struct StringId(u32);

/// GOOS pairs are mutable and have reference semantics.
/// A pair is represented by an index into the pair arena.
#[derive(Clone, Copy)]
struct PairId(u32);

/// GOOS closures (functions, including anonymous lambdas) also use an arena
/// since they have reference semantics and need garbage collection.
#[derive(Clone, Copy)]
struct ClosureId(u32);

/// The GOOS "environment" refers to a lexical environment binding Objects to symbolic names,
/// these are also arena-allocated to work with garbage collection.
#[derive(Clone, Copy)]
struct EnvId(u32);

/// GOOS symbols are either an interned symbol, or generated by `gensym`, which always produces
/// unique symbol names. To avoid increasing memory use in the symbol interner, gensyms are
/// represented by a unique integer rather than a unique string.
#[derive(Clone, Copy)]
enum Symbol {
    Interned(SymId),
    Gensym(u64),
}

/// GOOS object enum.
#[derive(Clone, Copy)]
enum Value {
    EmptyList,
    Integer(i64),
    Symbol(Symbol),
    Float(f32),
    String(StringId),
    Pair(PairId),
    Closure(ClosureId),
    Builtin(BuiltinId),
    Env(EnvId),
}

/// GOOS object with an optional reference to where it came from.
/// The current implementation isn't great on size, but it's simple.
struct Object {
    value: Value,
    span: Option<SpanRef>,
}

/// Arena-allocated and GC'd pair.
struct Pair {
    car: Object,
    cdr: Object,
}

/// Arena-allocated and GC'd environment.
struct Environment {
    parent: Option<EnvId>,
    bindings: BTreeMap<Symbol, Object>,
}

/// Arena-allocated and GC'd closure.
struct Closure {
    // TODO params
    body: Object,
    env: EnvId,
}

/// trait for types that index into an arena.
trait ArenaId: Copy {
    fn from_index(i: usize) -> Self;
    fn index(self) -> usize;
}

/// slot in an arena, either representing a Live (allocated) object, or an empty slot. The empty
/// slots store the index of the next free slot.
enum Slot<Id, T> {
    Live { value: T, marked: bool },
    Free(Option<Id>),
}

/// Arena allocator with free-list.
struct Arena<Id: ArenaId, T> {
    slots: Vec<Slot<Id, T>>,
    first_free: Option<Id>,
    allocated_count: usize,
}

/// Arenas for GOOS objects.
struct Heap {
    pairs: Arena<PairId, Pair>,
    strings: Arena<StringId, String>,
    envs: Arena<EnvId, Environment>,
    closures: Arena<ClosureId, Closure>,
    next_gc: usize,
}

impl ArenaId for PairId {
    fn from_index(i: usize) -> Self {
        Self(u32::try_from(i).unwrap())
    }
    fn index(self) -> usize {
        self.0 as usize
    }
}

impl ArenaId for StringId {
    fn from_index(i: usize) -> Self {
        Self(u32::try_from(i).unwrap())
    }
    fn index(self) -> usize {
        self.0 as usize
    }
}

impl ArenaId for EnvId {
    fn from_index(i: usize) -> Self {
        Self(u32::try_from(i).unwrap())
    }
    fn index(self) -> usize {
        self.0 as usize
    }
}

impl ArenaId for ClosureId {
    fn from_index(i: usize) -> Self {
        Self(u32::try_from(i).unwrap())
    }
    fn index(self) -> usize {
        self.0 as usize
    }
}

impl<Id: ArenaId, T> Arena<Id, T> {
    pub fn new() -> Self {
        Self {
            slots: Vec::new(),
            first_free: None,
            allocated_count: 0,
        }
    }

    /// Allocate a T from the arena, initializing it to value.
    pub fn alloc(&mut self, value: T) -> Id {
        // try the free list first.
        self.allocated_count += 1;
        if let Some(i) = self.first_free {
            let slot = &mut self.slots[i.index()];
            let Slot::Free(next) = slot else {
                unreachable!();
            };
            self.first_free = *next;
            *slot = Slot::Live {
                value,
                marked: false,
            };
            i
        } else {
            let i = self.slots.len();
            self.slots.push(Slot::Live {
                value,
                marked: false,
            });
            Id::from_index(i)
        }
    }

    /// Get a reference to a T from the arena by id.
    pub fn get(&self, i: Id) -> &T {
        match &self.slots[i.index()] {
            Slot::Live { value, .. } => value,
            Slot::Free(_) => unreachable!(),
        }
    }

    /// Get a mutable reference to a T from the arena by id.
    fn get_mut(&mut self, i: Id) -> &mut T {
        match &mut self.slots[i.index()] {
            Slot::Live { value, .. } => value,
            Slot::Free(_) => unreachable!(),
        }
    }

    /// GC function: mark a live slot as processed by the mark phase.
    fn mark(&mut self, i: Id) -> (bool, &T) {
        let Slot::Live { marked, value } = &mut self.slots[i.index()] else {
            panic!("attempted to mark a free slot.")
        };
        (std::mem::replace(marked, true), value)
    }

    /// GC function: iterate all slots. Clear the marker on marked slots, and free non-marked
    /// objects.
    fn sweep(&mut self) {
        for i in 0..self.slots.len() {
            match &mut self.slots[i] {
                Slot::Live { marked, .. } => {
                    if *marked {
                        *marked = false;
                    } else {
                        self.allocated_count -= 1;
                        self.slots[i] = Slot::Free(self.first_free);
                        self.first_free = Some(Id::from_index(i));
                    }
                }
                Slot::Free(_) => {}
            }
        }
    }
}

impl Heap {
    /// Minimum threshold object count for GC.
    const MIN_GC: usize = 32;

    /// Get the total number of allocated objects on the heap.
    pub fn allocated_count(&self) -> usize {
        self.pairs.allocated_count
            + self.strings.allocated_count
            + self.envs.allocated_count
            + self.closures.allocated_count
    }

    /// Check if the GC should run. Separate function from GC so the user can assemble the root
    /// list only if needed.
    pub fn needs_gc(&self) -> bool {
        self.allocated_count() > self.next_gc
    }

    /// Collect garbage.
    pub fn gc(&mut self, roots: &[&Object]) {
        // MARK - flag all known-live objects.
        let mut work: Vec<Value> = roots.iter().map(|x| x.value).collect();
        while let Some(x) = work.pop() {
            match x {
                Value::EmptyList => (),
                Value::Integer(_) => (),
                Value::Symbol(_) => (),
                Value::Float(_) => (),
                Value::Builtin(_) => (),
                Value::String(i) => {
                    self.strings.mark(i);
                }
                Value::Pair(i) => {
                    let (already_marked, value) = self.pairs.mark(i);
                    if !already_marked {
                        work.push(value.car.value);
                        work.push(value.cdr.value);
                    }
                }
                Value::Closure(i) => {
                    let (already_marked, value) = self.closures.mark(i);
                    if !already_marked {
                        // TODO add env parameters once we have them.
                        work.push(value.body.value);
                        work.push(Value::Env(value.env));
                    }
                }
                Value::Env(i) => {
                    let (already_marked, value) = self.envs.mark(i);
                    if !already_marked {
                        if let Some(parent) = value.parent {
                            work.push(Value::Env(parent));
                        }
                        for v in value.bindings.values() {
                            work.push(v.value);
                        }
                    }
                }
            }
        }

        // SWEEP
        self.pairs.sweep();
        self.strings.sweep();
        self.closures.sweep();
        self.envs.sweep();

        // next threshold set as 2x the surviving count.
        self.next_gc = Heap::MIN_GC.max(self.allocated_count() * 2);
    }
}
